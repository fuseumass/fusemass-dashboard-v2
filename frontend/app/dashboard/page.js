"use client";

import { ArrowRight, CircleCheck } from "lucide-react";
import Link from "next/link";
import { useEffect, useState } from "react";
import ApplicationStatusBadge from "@/components/ApplicationStatusBadge";
import PageHeader from "@/components/PageHeader";
import { CardSkeleton } from "@/components/skeletons";
import { Button } from "@/components/ui/button";
import {
  Card,
  CardAction,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { apiFetch } from "@/lib/api";
import { config } from "@/lib/config";
import { formatDateTime } from "@/lib/datetime";
import { useUser } from "@/lib/userContext";

const STATUS_LABELS = {
  draft: "Draft, not submitted",
  pending: "Submitted, under review",
  accepted: "Accepted",
  rejected: "Not accepted",
  waitlisted: "Waitlisted",
};

export default function DashboardHome() {
  const user = useUser();
  const [state, setState] = useState({
    loading: true,
    round: null,
    application: null,
  });
  const [qr, setQr] = useState(null);

  useEffect(() => {
    apiFetch("/api/applications/me")
      .then((data) =>
        setState({
          loading: false,
          round: data.round,
          application: data.application,
        }),
      )
      .catch(() =>
        setState({ loading: false, round: null, application: null }),
      );
    // Fetched on its own rather than off the open round's application: on
    // event day applications are closed, and that is exactly when it's needed.
    apiFetch("/api/applications/me/qr")
      .then((data) => setQr(data))
      .catch(() => setQr(null));
  }, []);

  return (
    <div>
      <PageHeader
        title={`Welcome, ${user.name.split(" ")[0]}`}
        description={`Your ${config.orgName} dashboard.`}
      />

      <div className="grid items-start gap-4 md:grid-cols-2">
        {state.loading
          ? <CardSkeleton lines={2} />
          : <Card>
              <CardHeader>
                <CardTitle>Application</CardTitle>
                {state.application
                  ? <CardAction>
                      <ApplicationStatusBadge
                        status={state.application.status}
                        label={
                          STATUS_LABELS[state.application.status] ||
                          state.application.status
                        }
                      />
                    </CardAction>
                  : null}
                {state.round
                  ? <CardDescription>{state.round.name} round</CardDescription>
                  : null}
              </CardHeader>
              <CardContent className="space-y-4">
                {!state.round
                  ? <p className="text-muted-foreground">
                      Applications aren&apos;t open right now. Check back soon.
                    </p>
                  : !state.application
                    ? <>
                        <p className="text-muted-foreground">
                          The {state.round.name} round is open. You haven&apos;t
                          applied yet.
                        </p>
                        <Button asChild>
                          <Link href="/dashboard/application">
                            Start your application
                          </Link>
                        </Button>
                      </>
                    : <Button asChild variant="outline">
                        <Link href="/dashboard/application">
                          View or edit your application
                          <ArrowRight
                            data-icon="inline-end"
                            aria-hidden="true"
                          />
                        </Link>
                      </Button>}
              </CardContent>
            </Card>}

        {qr
          ? <Card>
              <CardHeader>
                <CardTitle>Your check-in QR code</CardTitle>
                <CardDescription>
                  Show this at event check-in and at every meal. It&apos;s the
                  same code as in your acceptance email.
                </CardDescription>
              </CardHeader>
              <CardContent className="space-y-4">
                {user.checkedIn
                  ? <p className="flex items-center gap-1.5 font-medium text-success">
                      <CircleCheck className="size-4" aria-hidden="true" />
                      You&apos;re checked in
                      {user.checkedInAt
                        ? ` (${formatDateTime(user.checkedInAt)})`
                        : ""}
                    </p>
                  : null}
                {/* A data: URL generated by the API; next/image adds nothing here. */}
                {/* biome-ignore lint/performance/noImgElement: data URL, not a static asset */}
                <img
                  src={qr.qrCode}
                  alt="Your check-in QR code"
                  width={240}
                  height={240}
                  className="block size-60 rounded-md bg-white"
                />
              </CardContent>
            </Card>
          : null}
      </div>
    </div>
  );
}
