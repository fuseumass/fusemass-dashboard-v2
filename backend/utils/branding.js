"use strict";

/**
 * Runtime branding (B28). The effective branding is, per field:
 *
 *   admin setting (OrgSettings.branding)  ->  server env (BRAND_*, ORG_NAME)  ->  built-in default
 *
 * The env vars are read at REQUEST time, never at module load or build time,
 * so one image can serve every hackathon and a restart is all it takes to
 * change a default.
 *
 * Nothing here ever passes raw CSS through: colours must be exactly #RRGGBB and
 * URLs must be plain http(s) URLs. Anything else is rejected on write and
 * ignored on read (so a hand-edited database document can't inject styles or
 * `javascript:` links either).
 *
 * This file is pure (no database), so the schema can share the validators.
 */

// Used when neither the admin nor the server env sets a colour.
var DEFAULT_PRIMARY = "#4f46e5";
var DEFAULT_SECONDARY = "#64748b";

var HEX_COLOR = /^#[0-9a-fA-F]{6}$/;
var CONTROL_CHARS = /[\u0000-\u001f\u007f]/;
var MAX_ORG_NAME = 80;
var MAX_URL_LENGTH = 2048;

// Where uploaded images are served from: GET /api/meta/branding/files/<name>.
// The name is generated by us (slot + 16 random hex + extension); the serving
// route only accepts names of exactly this shape, so it can never be used to
// read some other blob from the container.
var FILE_NAME = /^(logo|logo-dark|favicon)-[0-9a-f]{16}\.(png|jpg|webp|ico)$/;

// The three image slots. `types` is what may be uploaded to each (never SVG).
var SLOTS = {
  logo: {
    urlField: "logoUrl",
    fileField: "logoFile",
    envUrl: "BRAND_LOGO_URL",
    types: ["png", "jpg", "webp"],
  },
  "logo-dark": {
    urlField: "logoDarkUrl",
    fileField: "logoDarkFile",
    envUrl: "BRAND_LOGO_DARK_URL",
    types: ["png", "jpg", "webp"],
  },
  favicon: {
    urlField: "faviconUrl",
    fileField: "faviconFile",
    envUrl: "BRAND_FAVICON_URL",
    types: ["png", "ico", "jpg", "webp"],
  },
};
var SLOT_NAMES = Object.keys(SLOTS);

var COLOR_FIELDS = ["primaryColor", "secondaryColor", "accentColor"];
var EDITABLE_FIELDS = ["orgName"].concat(COLOR_FIELDS, ["logoUrl", "logoDarkUrl", "faviconUrl"]);

// Env vars that held an invalid value, so each is only warned about once.
var warned = {};

/**
 * Whether a string is exactly a #RRGGBB colour (no #RGB, no alpha, no names).
 * @param {*} value
 * @returns {boolean}
 */
function isHexColor(value) {
  return typeof value === "string" && HEX_COLOR.test(value);
}

/**
 * Validate a plain http(s) URL. Rejects other schemes (javascript:, data:,
 * file:), embedded credentials, whitespace and absurd lengths.
 * @param {*} value - Candidate URL.
 * @param {boolean} allowHttp - Accept http:// as well as https:// (server env only).
 * @returns {string|null} The normalised URL, or null when it isn't acceptable.
 */
function cleanUrl(value, allowHttp) {
  if (typeof value !== "string") {
    return null;
  }
  var text = value.trim();
  if (!text || text.length > MAX_URL_LENGTH || /\s/.test(text) || CONTROL_CHARS.test(text)) {
    return null;
  }
  var parsed;
  try {
    parsed = new URL(text);
  } catch (err) {
    return null;
  }
  var okProtocol = parsed.protocol === "https:" || (allowHttp && parsed.protocol === "http:");
  if (!okProtocol || parsed.username || parsed.password || !parsed.hostname) {
    return null;
  }
  return parsed.href;
}

/**
 * Prefix for URLs of uploaded images: the API's public address when
 * API_PUBLIC_URL is set, otherwise "" (a root-relative path the frontend
 * resolves against its API URL). Deliberately NOT derived from the request's
 * Host header: the response is shared-cacheable and a forged Host would poison it.
 * @returns {string} No trailing slash.
 */
function publicBase() {
  var base = cleanUrl(process.env.API_PUBLIC_URL, true);
  return base ? base.replace(/\/+$/, "") : "";
}

/**
 * Public URL of an uploaded image.
 * @param {string} fileName - A stored file name (see FILE_NAME).
 * @returns {string|null} The URL, or null when the name isn't a valid one.
 */
function fileUrl(fileName) {
  if (typeof fileName !== "string" || !FILE_NAME.test(fileName)) {
    return null;
  }
  return publicBase() + "/api/meta/branding/files/" + fileName;
}

/**
 * Read a colour default from the server env, ignoring (and warning once about)
 * a malformed value instead of passing it on.
 * @param {string} name - Env var name, e.g. "BRAND_PRIMARY".
 * @returns {string|null} Lower-case #rrggbb, or null.
 */
function envColor(name) {
  var raw = process.env[name];
  if (raw === undefined || raw === "") {
    return null;
  }
  var value = String(raw).trim();
  if (isHexColor(value)) {
    return value.toLowerCase();
  }
  if (!warned[name]) {
    warned[name] = true;
    console.warn(name + " is not a #RRGGBB colour; ignoring it.");
  }
  return null;
}

/**
 * @param {string} text - Organisation name candidate.
 * @returns {string} The trimmed name, or "" when it is empty/unusable.
 */
function cleanName(text) {
  if (typeof text !== "string") {
    return "";
  }
  var name = text.trim();
  return name.length > MAX_ORG_NAME || CONTROL_CHARS.test(name) ? "" : name;
}

/**
 * Compute the effective branding the frontend should apply.
 * @param {object|null} settings - An OrgSettings document or plain object (may be null/empty).
 * @returns {object} { orgName, primaryColor, secondaryColor, accentColor|null, logoUrl|null, logoDarkUrl|null, faviconUrl|null }
 */
function resolve(settings) {
  var stored = (settings && settings.branding) || {};

  function color(field, envName, fallback) {
    var own = stored[field];
    return (isHexColor(own) ? own.toLowerCase() : null) || envColor(envName) || fallback;
  }
  function image(slot) {
    var cfg = SLOTS[slot];
    return (
      fileUrl(stored[cfg.fileField]) ||
      cleanUrl(stored[cfg.urlField], false) ||
      cleanUrl(process.env[cfg.envUrl], true) ||
      null
    );
  }

  return {
    orgName: cleanName(stored.orgName) || cleanName(process.env.ORG_NAME || "") || "Hackathon",
    primaryColor: color("primaryColor", "BRAND_PRIMARY", DEFAULT_PRIMARY),
    secondaryColor: color("secondaryColor", "BRAND_SECONDARY", DEFAULT_SECONDARY),
    accentColor: color("accentColor", "BRAND_ACCENT", null),
    logoUrl: image("logo"),
    logoDarkUrl: image("logo-dark"),
    faviconUrl: image("favicon"),
  };
}

/**
 * Validate the `branding` object of a settings PATCH. Partial: only the keys
 * present change. An empty string or null clears a field back to the server
 * default. Unknown keys are rejected so typos are noticed.
 *
 * Setting an image URL for a slot also drops the image uploaded to that slot
 * (one source at a time), reported in `replacedSlots` so the controller can
 * delete the stored file.
 * @param {*} input - req.body.branding.
 * @returns {{errors: string[], update: object, replacedSlots: string[]}} `update` maps "branding.<field>" to its new value.
 */
function validatePatch(input) {
  var errors = [];
  var update = {};
  var replacedSlots = [];
  if (!input || typeof input !== "object" || Array.isArray(input)) {
    return { errors: ["branding must be an object."], update: update, replacedSlots: replacedSlots };
  }

  Object.keys(input).forEach(function each(field) {
    var value = input[field];
    var clearing = value === null || value === "";

    if (EDITABLE_FIELDS.indexOf(field) === -1) {
      errors.push("Unknown branding field \"" + field + "\".");
    } else if (clearing) {
      update["branding." + field] = "";
    } else if (field === "orgName") {
      if (typeof value !== "string" || !cleanName(value)) {
        errors.push("orgName must be 1-" + MAX_ORG_NAME + " characters of plain text.");
      } else {
        update["branding.orgName"] = cleanName(value);
      }
    } else if (COLOR_FIELDS.indexOf(field) !== -1) {
      if (!isHexColor(value)) {
        errors.push(field + " must be a colour written as #RRGGBB (for example #4f46e5).");
      } else {
        update["branding." + field] = value.toLowerCase();
      }
    } else {
      // A logo/favicon URL. Admin-supplied URLs must be https (mixed content).
      var url = cleanUrl(value, false);
      if (!url) {
        errors.push(field + " must be an https:// URL.");
      } else {
        update["branding." + field] = url;
        SLOT_NAMES.forEach(function eachSlot(slot) {
          if (SLOTS[slot].urlField === field) {
            update["branding." + SLOTS[slot].fileField] = "";
            replacedSlots.push(slot);
          }
        });
      }
    }
  });

  return { errors: errors, update: update, replacedSlots: replacedSlots };
}

module.exports = {
  DEFAULT_PRIMARY: DEFAULT_PRIMARY,
  DEFAULT_SECONDARY: DEFAULT_SECONDARY,
  MAX_ORG_NAME: MAX_ORG_NAME,
  FILE_NAME: FILE_NAME,
  SLOTS: SLOTS,
  SLOT_NAMES: SLOT_NAMES,
  isHexColor: isHexColor,
  cleanUrl: cleanUrl,
  fileUrl: fileUrl,
  resolve: resolve,
  validatePatch: validatePatch,
};
